(* Generates conformance test vectors for elykseer-cpp with the extracted
   implementation of elykseer-ml (the reference). Writes a C++ header to stdout.

   Run with tests/conformance/generate.sh <path to elykseer-ml> *)

open Mlcpp_cstdio
module L = Elykseer__Lxr

let my_id = "conformance-0123"
let aid = Elykseer_crypto.Sha3_256.string "elykseer-cpp conformance aid"
let pkey = "000102030405060708090a0b0c0d0e0f101112131415161718191a1b1c1d1e1f"
let ivec = "f0f1f2f3f4f5f6f7f8f9fafbfcfdfeff"
let nchunks = 16

(* deterministic content: byte i = (i * mul + add) mod 256 *)
let blocks = [ (40000, 7, 3); (60000, 13, 5); (32768, 31, 11) ]

let config ?(n = nchunks) chunkpath : L.Configuration.configuration =
  { L.Configuration.config_nchunks = L.Nchunks.from_int n
  ; path_chunks = chunkpath
  ; path_db = chunkpath
  ; my_id
  ; trace = L.Tracer.nullTracer }

let content (sz, mul, add) =
  L.Cstdio.BufferPlain.from_buffer (Cstdio.File.Buffer.init sz (fun i -> Char.chr ((i * mul + add) mod 256)))

let fail msg = prerr_endline msg; exit 1

(* the commit of the elykseer-ml checkout, if known *)
let ml_commit () =
  try
    let ic = Unix.open_process_in "git describe --tags --always --dirty 2>/dev/null" in
    let c = try input_line ic with End_of_file -> "" in
    ignore (Unix.close_process_in ic);
    if c = "" then "unknown" else c
  with _ -> "unknown"

let () =
  let chunkpath = Filename.concat (Filename.get_temp_dir_name ())
                    ("lxr_conformance_" ^ string_of_int (Unix.getpid ())) in
  let c = config chunkpath in
  let p = Printf.printf in
  p "// generated by tests/conformance/gen_vectors.ml with elykseer-ml %s (%s); do not edit\n" L.Version.version (ml_commit ());
  p "#pragma once\n\n#include <cstdint>\n\nnamespace conformance {\n\n";
  p "constexpr const char *ml_version = \"%s\";\n" L.Version.version;
  p "constexpr const char *my_id = \"%s\";\n" my_id;
  p "constexpr const char *aid = \"%s\";\n" aid;
  p "constexpr const char *pkey = \"%s\";\n" pkey;
  p "constexpr const char *ivec = \"%s\";\n" ivec;
  p "constexpr int nchunks = %d;\n\n" nchunks;

  (* header length = initial apos *)
  p "struct Header { int nchunks; uint32_t apos; };\nconstexpr Header headers[] = {\n";
  List.iter (fun n ->
      let a, _ = L.Assembly.AssemblyPlainWritable.create (config ~n chunkpath) in
      p "  { %d, %d },\n" n (L.Conversion.n2i a.L.Assembly.apos))
    [16; 17; 32; 143; 144; 145; 256];
  p "};\n\n";

  (* an assembly of 16 chunks (no random header) with the given aid *)
  let a0, b0 = L.Assembly.AssemblyPlainWritable.create c in
  if L.Conversion.n2i a0.L.Assembly.apos <> 0 then fail "unexpected header";
  let a0 = { a0 with L.Assembly.aid = aid } in
  let (an, bis, _) = List.fold_left (fun (a, bis, fpos) ((sz, _, _) as blk) ->
      let a', bi = L.Assembly.backup a b0 (L.Conversion.i2n fpos) (content blk) in
      (a', bi :: bis, fpos + sz)) (a0, [], 0) blocks in
  let bis = List.rev bis in
  p "struct Block { uint32_t size; int mul; int add; uint64_t filepos; uint32_t apos; const char *checksum; };\nconstexpr Block blocks[] = {\n";
  List.iter2 (fun (sz, mul, add) (bi : L.Assembly.blockinformation) ->
      p "  { %d, %d, %d, %d, %d, \"%s\" },\n" sz mul add
        (L.Conversion.n2i bi.filepos) (L.Conversion.n2i bi.blockapos) bi.bchecksum)
    blocks bis;
  p "};\n\n";

  let af, bf = L.Assembly.finish an b0 in
  let ki = { L.Assembly.ivec = ivec; pkey; localnchunks = L.Conversion.i2p nchunks } in
  let ae, be = match L.Assembly.encrypt af bf ki with
    | None -> fail "encryption failed"
    | Some r -> r in
  let nw = L.Assembly.extract c ae be in
  if L.Conversion.n2i nw <> nchunks * 262144 then fail "extract failed";
  p "// chunk files: path below the chunk directory and SHA3-256 of the content\n";
  p "struct Chunk { int cid; const char *path; const char *sha3; };\nconstexpr Chunk chunks[] = {\n";
  let prefix = chunkpath ^ "/" in
  for cid = 1 to nchunks do
    let fp = L.Assembly.chunk_identifier_path c aid (L.Conversion.i2p cid) in
    let rel = String.sub fp (String.length prefix) (String.length fp - String.length prefix) in
    p "  { %d, \"%s\", \"%s\" },\n" cid rel (Elykseer_crypto.Sha3_256.file fp)
  done;
  p "};\n\n";

  (* the reference can read its own chunks back *)
  let a_r = { L.Assembly.nchunks = L.Nchunks.from_int nchunks; aid; apos = L.Conversion.i2n 0 } in
  (match L.Assembly.recall c a_r with
   | None -> fail "recall failed"
   | Some (a1, b1) ->
     match L.Assembly.decrypt a1 b1 ki with
     | None -> fail "decrypt failed"
     | Some (_, b2) ->
       List.iter (fun bi -> if L.Assembly.restore b2 bi = None then fail "restore failed") bis);

  (* file hash = sha3_256(fname ^ my_id) *)
  p "struct FHash { const char *fname; const char *fhash; };\nconstexpr FHash fhashes[] = {\n";
  Sys.mkdir "sub dir" 0o755;
  List.iter (fun fn ->
      let oc = open_out fn in output_string oc "conformance\n"; close_out oc;
      let fi = L.Filesupport.get_file_information c fn in
      Sys.remove fn;
      p "  { \"%s\", \"%s\" },\n" fn fi.L.Filesupport.fhash)
    [ "conformance.txt"; "sub dir/file with spaces.bin" ];
  Sys.rmdir "sub dir";
  p "};\n\n} // namespace conformance\n";
  ignore (Sys.command ("rm -rf " ^ Filename.quote chunkpath))
